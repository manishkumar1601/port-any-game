// Generates per-agent wrappers from the canonical subagents in agents/*.md (Claude format: name, description, tools).
// `node scripts/gen-wrappers.mjs` writes them (the output is committed); `--check` exits 1 on any drift (validate runs it).
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Claude tool -> Copilot tool alias, and -> OpenCode v2 permission action (note 06 §4/§5.3). Bash is handled separately.
const COPILOT = { Read: 'read', Glob: 'search', Grep: 'search', Bash: 'execute', Write: 'edit', Edit: 'edit', MultiEdit: 'edit', WebFetch: 'web', WebSearch: 'web' };
const OPENCODE = { Read: 'read', Glob: 'glob', Grep: 'grep', Write: 'edit', Edit: 'edit', MultiEdit: 'edit', WebFetch: 'webfetch', WebSearch: 'websearch' };
// Directories that hold only generated files: anything here the generator does not produce is stale.
const GENERATED = [['com.github.copilot/agents', /\.agent\.md$/], ['opencode/agents', /\.md$/], ['opencode/commands', /\.md$/]];
const PORT_GAME = `---
# generated by scripts/gen-wrappers.mjs; edit the generator, then run: npm run gen
description: "Port a PC game you own to a private browser build (survey, lane, build, verify)"
agent: build
---
@port-any-game Port the game in: $ARGUMENTS
`;
const q = JSON.stringify; // a JSON string or array is also valid YAML

function parse(text) {
  const t = text.replace(/\r\n/g, '\n');
  const m = /^---\n([\s\S]*?)\n---\n/.exec(t);
  if (!m) throw new Error('missing frontmatter');
  const fm = {};
  for (const line of m[1].split('\n')) {
    const kv = /^([\w-]+):\s*(.*)$/.exec(line);
    if (kv) fm[kv[1]] = kv[2].startsWith('"') ? JSON.parse(kv[2]) : kv[2];
  }
  return { fm, body: t.slice(m[0].length) };
}

export function generate(rootDir) {
  const out = new Map();
  for (const f of readdirSync(path.join(rootDir, 'agents')).filter((n) => n.endsWith('.md')).sort()) {
    const { fm, body } = parse(readFileSync(path.join(rootDir, 'agents', f), 'utf8'));
    const tools = fm.tools.split(',').map((t) => t.trim()).filter(Boolean);
    const head = `---\n# generated by scripts/gen-wrappers.mjs from agents/${f}; edit that file, then run: npm run gen\n`;
    out.set(`com.github.copilot/agents/${fm.name}.agent.md`,
      `${head}name: ${fm.name}\ndescription: ${q(fm.description)}\ntools: ${q([...new Set(tools.map((t) => COPILOT[t] ?? t.toLowerCase()))])}\n---\n${body}`);
    // v2 permissions, last match wins: deny everything, then allow the canonical tools; Bash only for the pag commands
    // the instructions run.
    const actions = [...new Set(tools.map((t) => OPENCODE[t]).filter(Boolean))];
    const perms = [['*', '*', 'deny'], ...actions.map((a) => [a, '*', 'allow'])];
    if (tools.includes('Read')) perms.push(['external_directory', '*', 'ask']); // the game and port folders sit outside the project
    if (tools.includes('Bash')) {
      for (const c of [...new Set([...body.matchAll(/\bpag\.mjs ([a-z][\w-]*)/g)].map((m) => m[1]))].sort()) perms.push(['shell', `node *pag.mjs ${c}*`, 'allow']);
    }
    out.set(`opencode/agents/${fm.name}.md`,
      `${head}description: ${q(fm.description)}\nmode: subagent\npermissions:\n${perms.map(([a, r, e]) => `  - { action: ${q(a)}, resource: ${q(r)}, effect: ${q(e)} }`).join('\n')}\n---\n${body}`);
  }
  out.set('opencode/commands/port-game.md', PORT_GAME);
  return out;
}

const stale = (rootDir, files) => GENERATED.flatMap(([dir, re]) => (existsSync(path.join(rootDir, dir))
  ? readdirSync(path.join(rootDir, dir)).filter((n) => re.test(n)).map((n) => `${dir}/${n}`).filter((rel) => !files.has(rel))
  : []));

// Generated paths whose file is missing, different or stale.
export function drift(rootDir) {
  const files = generate(rootDir);
  const differs = ([rel, text]) => { try { return readFileSync(path.join(rootDir, rel), 'utf8').replace(/\r\n/g, '\n') !== text; } catch { return true; } };
  return [...[...files].filter(differs).map(([rel]) => rel), ...stale(rootDir, files)];
}

export function write(rootDir) {
  const files = generate(rootDir);
  for (const rel of stale(rootDir, files)) rmSync(path.join(rootDir, rel));
  for (const [rel, text] of files) {
    mkdirSync(path.dirname(path.join(rootDir, rel)), { recursive: true });
    writeFileSync(path.join(rootDir, rel), text);
  }
  return [...files.keys()];
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  if (process.argv.includes('--check')) {
    const d = drift(root);
    if (d.length) { console.error(`gen-wrappers: out of date (run: npm run gen):\n  ${d.join('\n  ')}`); process.exit(1); }
    console.log('gen-wrappers: ok');
  } else {
    for (const rel of write(root)) console.log(`wrote ${rel}`);
  }
}
